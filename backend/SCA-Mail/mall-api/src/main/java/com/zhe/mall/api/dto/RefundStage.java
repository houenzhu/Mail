package com.zhe.mall.api.dto;

/**
 * 退款阶段（支付侧 → 订单侧的语义契约，28.5）。
 *
 * <p>支付侧有 4 种退款状态（0 待审核 / 10 退款中 / 20 成功 / 30 失败），订单侧只需要三种结果，
 * 用本枚举做一次收敛，避免把支付侧状态机细节复制到订单侧（服务边界见 17.2）。
 */
public enum RefundStage {

    /** 已受理，进入退款中：订单 20 → 60 */
    REFUNDING,

    /** 渠道退款成功：订单 60 → 70 */
    REFUNDED,

    /** 渠道退款失败（驳回）：订单 60 → 20，用户可再次申请 */
    REJECTED
}
